#!/usr/bin/env python3
"""Generate deterministic two-body LHE events for plumbing tests only."""

from __future__ import annotations

import argparse
import math
import random
from pathlib import Path


def particle_line(pid, status, m1, m2, c1, c2, px, py, pz, energy, mass, spin):
    return (
        f" {pid:9d} {status:3d} {m1:4d} {m2:4d} {c1:4d} {c2:4d}"
        f" {px: .10e} {py: .10e} {pz: .10e} {energy: .10e}"
        f" {mass: .10e} 0.0000000000e+00 {spin: .1f}"
    )


def main() -> int:
    ap = argparse.ArgumentParser(description="Toy gg -> LLP LLP LHE generator")
    ap.add_argument("--pdg", type=int, default=9900035)
    ap.add_argument("--mass-gev", type=float, default=250.0)
    ap.add_argument("--events", type=int, default=500)
    ap.add_argument("--sqrt-shat-gev", type=float, default=1000.0)
    ap.add_argument("--seed", type=int, default=13001)
    ap.add_argument("--output", type=Path, required=True)
    args = ap.parse_args()

    if args.sqrt_shat_gev <= 2.0 * args.mass_gev:
        raise SystemExit("sqrt(shat) must exceed 2*m")
    if args.events <= 0:
        raise SystemExit("events must be positive")

    rng = random.Random(args.seed)
    e = args.sqrt_shat_gev / 2.0
    p = math.sqrt(e * e - args.mass_gev * args.mass_gev)
    spin = 9.0 if abs(args.pdg) == 9900035 else 1.0

    lines = [
        '<LesHouchesEvents version="3.0">',
        '<header>',
        '<!-- TOY_LHE_PLUMBING_TEST: not generated by MadGraph. -->',
        '</header>',
        '<init>',
        ' 2212 2212 6.5000000000e+03 6.5000000000e+03 0 0 230000 230000 3 1',
        ' 1.0000000000e-03 0.0000000000e+00 1.0000000000e+00 1',
        '</init>',
    ]

    for _ in range(args.events):
        cos_theta = rng.uniform(-0.85, 0.85)
        sin_theta = math.sqrt(1.0 - cos_theta * cos_theta)
        phi = rng.uniform(-math.pi, math.pi)
        px = p * sin_theta * math.cos(phi)
        py = p * sin_theta * math.sin(phi)
        pz = p * cos_theta
        lines.extend(
            [
                '<event>',
                f' 4 1 1.0000000000e+00 {args.sqrt_shat_gev:.10e} 7.2973525693e-03 1.0000000000e-01',
                particle_line(21, -1, 0, 0, 501, 502, 0.0, 0.0, e, e, 0.0, 9.0),
                particle_line(21, -1, 0, 0, 502, 501, 0.0, 0.0, -e, e, 0.0, 9.0),
                particle_line(args.pdg, 1, 1, 2, 0, 0, px, py, pz, e, args.mass_gev, spin),
                particle_line(args.pdg, 1, 1, 2, 0, 0, -px, -py, -pz, e, args.mass_gev, spin),
                '</event>',
            ]
        )

    lines.append('</LesHouchesEvents>')
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"[OK] {args.output}: {args.events} toy events, PDG={args.pdg}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
